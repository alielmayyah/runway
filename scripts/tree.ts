// Generates TREE.md: a Mermaid diagram of every path through the decisions in src/data/cards.ts.
//
//   npm run tree         rewrite TREE.md
//   npm run tree:check   exit with an error if TREE.md is out of date (used in CI)

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { CARDS, CHARACTERS } from '../src/data/cards.ts'
import { METERS, applyEffects, findEnding, initialMeters, winEnding } from '../src/game/engine.ts'
import type { Effects, Meters } from '../src/types.ts'

const OUT = fileURLToPath(new URL('../TREE.md', import.meta.url))

/** Escapes text for a quoted Mermaid label. */
const esc = (s: string) => s.replaceAll('"', '#quot;')

const formatEffects = (effects: Effects) =>
  METERS.filter((m) => effects[m.key])
    .map((m) => `${m.icon} ${effects[m.key]! > 0 ? '+' : '−'}${Math.abs(effects[m.key]!)}`)
    .join('  ')

const formatMeters = (meters: Meters) => METERS.map((m) => `${m.icon} ${meters[m.key]}`).join('  ')

interface Leaf {
  path: string[]
  meters: Meters
  title: string
  gameOver: boolean
}

function build() {
  const lines: string[] = []
  const leaves: Leaf[] = []
  let nextId = 0

  // Walks every combination of choices, adding a node per decision and per ending.
  // Each edge is written before its subtree so the diagram reads top-down, A before B.
  function walk(id: string, index: number, meters: Meters, path: string[]) {
    const card = CARDS[index]
    const who = CHARACTERS[card.who]
    lines.push(
      `  ${id}["${esc(`<b>Age ${card.age}</b><br/>${who.avatar} <b>${who.name}</b> · ${who.role}<br/>${card.text}`)}"]:::decision`,
    )

    card.choices.forEach((choice, i) => {
      const label = 'ABCDEFGHI'[i]
      const { meters: next } = applyEffects(meters, choice.effects)
      const nextPath = [...path, label]
      const ending = findEnding(next)
      const child = `n${nextId++}`

      lines.push(`  ${id} -->|"${esc(`<b>${label}.</b> ${choice.label}<br/>${formatEffects(choice.effects)}`)}"| ${child}`)

      if (ending || index + 1 === CARDS.length) {
        const result = ending ?? winEnding(next)
        const heading = ending ? `☠️ GAME OVER: ${result.title}` : `${result.mark} ${result.title}`
        lines.push(`  ${child}["${esc(`<b>${heading}</b><br/>${formatMeters(next)}`)}"]:::${ending ? 'lose' : 'win'}`)
        leaves.push({ path: nextPath, meters: next, title: result.title, gameOver: Boolean(ending) })
      } else {
        walk(child, index + 1, next, nextPath)
      }
    })
  }

  walk(`n${nextId++}`, 0, initialMeters(), [])
  return { lines, leaves }
}

function render() {
  const { lines, leaves } = build()
  const start = formatMeters(initialMeters())
  const header = ['Path', ...METERS.map((m) => `${m.icon} ${m.label}`), 'Result']

  return `# Decision tree

<!-- Generated by scripts/tree.ts from src/data/cards.ts. Don't edit by hand: run \`npm run tree\`. -->

Every path through the game's ${CARDS.length} decisions. Every meter starts at ${initialMeters().health} (${start}). A path ends early if a meter hits 0 or 100.

\`\`\`mermaid
flowchart TD
${lines.join('\n')}

  classDef decision fill:#fffdf8,stroke:#2d6a4f,stroke-width:2px,color:#1f1c17
  classDef win fill:#d8f3dc,stroke:#2d6a4f,stroke-width:2px,color:#1b4332
  classDef lose fill:#fde2df,stroke:#c0392b,stroke-width:2px,color:#7a1f15
\`\`\`

## All paths

| ${header.join(' | ')} |
| ${header.map(() => '---').join(' | ')} |
${leaves
  .map((l) => `| ${l.path.join(' → ')} | ${METERS.map((m) => l.meters[m.key]).join(' | ')} | ${l.gameOver ? `☠️ **${l.title}** (game over)` : l.title} |`)
  .join('\n')}

${leaves.length} paths: ${leaves.filter((l) => l.gameOver).length} end in a game over, and ${leaves.filter((l) => !l.gameOver).length} make it through.
`
}

const content = render()

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8').replaceAll('\r\n', '\n')
  } catch {
    // Missing file counts as out of date.
  }
  if (current !== content) {
    console.error('TREE.md is out of date. Run `npm run tree` and commit the result.')
    process.exit(1)
  }
  console.log('TREE.md is up to date.')
} else {
  writeFileSync(OUT, content)
  console.log('Wrote TREE.md')
}
